#!/usr/bin/env node
'use strict';

/**
 * Glimpse catalog health check: validates YouTube videos in the catalog.
 * Run with --validate to check all videos (slow, makes network requests).
 * Run with --fix to filter the catalog and write a validated version.
 */

const { seedCatalog } = require('../lib/cortexGlimpse/catalog');
const {
  batchValidateYouTube,
  partitionByValidation,
  catalogHealthReport
} = require('../lib/cortexGlimpse/youtubeValidation');

async function main() {
  const args = process.argv.slice(2);
  const validate = args.includes('--validate');
  const fix = args.includes('--fix');
  const verbose = args.includes('--verbose') || args.includes('-v');

  const catalog = seedCatalog();
  console.log(`Glimpse catalog: ${catalog.length} items`);

  const ytIds = catalog
    .map((item) => item.source && item.source.youtubeVideoId)
    .filter(Boolean);
  const uniqueIds = [...new Set(ytIds)];
  console.log(`Unique YouTube IDs: ${uniqueIds.length}`);

  if (!validate && !fix) {
    console.log('\nRun with --validate to check video embeddability (makes network requests).');
    console.log('Run with --fix to generate a filtered catalog.');
    return;
  }

  if (validate || fix) {
    console.log('\nValidating YouTube videos (this may take a minute)...');
    const results = await batchValidateYouTube(uniqueIds, {
      concurrency: 8,
      timeoutMs: 8000
    });

    const partition = partitionByValidation(catalog, results);
    const report = catalogHealthReport(partition);

    console.log('\n=== CATALOG HEALTH REPORT ===');
    console.log(`Total items: ${report.total}`);
    console.log(`Valid (embeddable): ${report.valid} (${report.validPercent}%)`);
    console.log(`Invalid: ${report.invalid}`);
    console.log('\nInvalid reasons:');
    for (const [reason, count] of Object.entries(report.reasons)) {
      console.log(`  ${reason}: ${count}`);
    }

    if (verbose || report.invalid > 0) {
      console.log('\nInvalid items:');
      for (const item of report.invalidItems) {
        console.log(`  - ${item.id}: ${item.title} (${item.ytId}) - ${item.reason}`);
      }
    }

    if (fix) {
      console.log('\n=== FIX MODE ===');
      const fs = require('fs');
      const path = require('path');
      const deadIdsPath = path.join(__dirname, '../lib/cortexGlimpse/deadYouTubeIds.js');
      
      const deadIds = report.invalidItems.map(item => item.ytId).filter(Boolean);
      const sortedIds = [...new Set(deadIds)].sort();
      
      const fileContent = `'use strict';

/**
 * Known non-embeddable YouTube video IDs.
 * Auto-generated by scripts/glimpse-catalog-health.js --fix
 * Last updated: ${new Date().toISOString().split('T')[0]}
 */

const DEAD_YOUTUBE_IDS = new Set([
${sortedIds.map(id => `  '${id}'`).join(',\n')}
]);

module.exports = { DEAD_YOUTUBE_IDS };
`;
      
      fs.writeFileSync(deadIdsPath, fileContent, 'utf8');
      console.log(`Wrote ${sortedIds.length} dead YouTube IDs to ${deadIdsPath}`);
      console.log('The catalog runtime will now filter these IDs via ytOk().');
    }

    if (report.invalid > 0) {
      process.exit(1);
    }
  }
}

main().catch((err) => {
  console.error('Error:', err);
  process.exit(1);
});
